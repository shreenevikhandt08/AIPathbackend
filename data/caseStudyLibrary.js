function pickCaseFromLibrary(absDay = 0, usedIds = [], weekNum = 1) {
  const used = new Set((usedIds || []).map(String));
  const preferred = CASE_STUDY_LIBRARY.filter(
    (c) => Number(c.weekHint || 1) === Number(weekNum || 1) && !used.has(String(c.id))
  );
  const pool =
    preferred.length
      ? preferred
      : CASE_STUDY_LIBRARY.filter((c) => !used.has(String(c.id)));
  const list = pool.length ? pool : CASE_STUDY_LIBRARY;
  const pick = list[Math.max(0, Number(absDay) || 0) % list.length];
  return {
    id: pick.id,
    title: pick.title,
    theme: pick.theme,
    company: pick.company,
    link: pick.link,
    what: pick.what,
    why: pick.why,
    lesson: pick.lesson,
    blurb: `${pick.what} ${pick.why} Lesson: ${pick.lesson}`,
  };
}

module.exports = { CASE_STUDY_LIBRARY, pickCaseFromLibrary };
